# =========================================
def calculate_order(products, payment_preference):
    if not isinstance(products, list) or not products:
        raise ValueError("Your shopping bag is empty.")
    if payment_preference not in ALLOWED_PAYMENT_PREFERENCES:
        raise ValueError("Please select a valid payment preference.")
    subtotal = 0
    verified_products = []
    for product in products:
        if not isinstance(product, dict):
            raise ValueError("Invalid product information.")
        product_name = str(product.get("name", "")).strip().upper()
        if product_name not in PRODUCT_CATALOG:
            raise ValueError(f"{product_name or 'This product'} is currently unavailable.")
        quantity = product.get("quantity", 1)
        if isinstance(quantity, bool) or not isinstance(quantity, int) or not 1 <= quantity <= 20:
            raise ValueError("Product quantity must be between 1 and 20.")
        size = str(product.get("size", "")).strip()
        if not size or len(size) > 30:
            raise ValueError("Please select a valid product size.")
        price = PRODUCT_CATALOG[product_name]
        product_total = price * quantity
        subtotal += product_total
        verified_products.append({
            "name": product_name.title(), "size": size, "quantity": quantity,
            "price": f"PKR {price:,}", "unit_price": price, "product_total": product_total
        })
    total = subtotal + SHIPPING_CHARGES
    if payment_preference == "Full Payment":
        advance, remaining, delivery_amount = total, 0, 0
    else:
        advance = round(subtotal / 2)
        remaining = subtotal - advance
        delivery_amount = remaining + SHIPPING_CHARGES
    return {
        "products": verified_products, "subtotal": subtotal, "shipping": SHIPPING_CHARGES,
        "advance": advance, "remaining": remaining, "delivery_amount": delivery_amount, "total": total
    }


def validate_payment_screenshot(file):
    if not file or not file.filename:
        raise ValueError("Please upload your payment screenshot.")
    filename = secure_filename(file.filename)
    extension = os.path.splitext(filename)[1].lower()
    if extension not in (".jpg", ".jpeg", ".png", ".webp"):
        raise ValueError("Only JPG, PNG and WEBP screenshots are allowed.")
    file_bytes = file.read()
    if not file_bytes or len(file_bytes) > 5 * 1024 * 1024:
        raise ValueError("Screenshot must be non-empty and smaller than 5 MB.")
    valid = (file_bytes.startswith(b"\xff\xd8\xff") or file_bytes.startswith(b"\x89PNG\r\n\x1a\n") or (file_bytes.startswith(b"RIFF") and file_bytes[8:12] == b"WEBP"))
    if not valid:
        raise ValueError("The uploaded file is not a valid image.")
    return file_bytes, extension

def save_payment_proof(image_bytes, extension):
    if CLOUDINARY_CONFIGURED:
        result = cloudinary.uploader.upload(
            image_bytes, folder="jora_edit/payment_proofs", resource_type="image",
            type="authenticated", format=extension.lstrip(".")
        )
        return "cloudinary:" + result["public_id"]
    if IS_RENDER:
        raise RuntimeError("Payment screenshot storage is not configured. Add Cloudinary credentials before accepting orders.")
    filename = secrets.token_hex(16) + extension
    with open(os.path.join(LOCAL_PROOF_DIR, filename), "wb") as image_file:
        image_file.write(image_bytes)
    return "local:" + filename


