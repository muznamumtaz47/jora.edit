def create_database():
    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_name TEXT NOT NULL,
                phone TEXT NOT NULL,
                email TEXT,
                city TEXT NOT NULL,
                address TEXT NOT NULL,
                payment_method TEXT NOT NULL,
                products TEXT NOT NULL,
                order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                status TEXT NOT NULL DEFAULT 'Pending',
                subtotal BIGINT NOT NULL DEFAULT 0,
                shipping BIGINT NOT NULL DEFAULT 300,
                advance BIGINT NOT NULL DEFAULT 0,
                remaining BIGINT NOT NULL DEFAULT 0,
                delivery_amount BIGINT NOT NULL DEFAULT 0,
                total BIGINT NOT NULL DEFAULT 0,
                payment_status TEXT NOT NULL DEFAULT 'Pending Verification',
                email_sent_at TEXT DEFAULT NULL,
                payment_preference TEXT NOT NULL DEFAULT '50% Advance',
                transaction_id TEXT DEFAULT NULL,
                payment_proof TEXT DEFAULT NULL
            )
        """)
        migrations = {
            "status": "TEXT NOT NULL DEFAULT 'Pending'",
            "subtotal": "BIGINT NOT NULL DEFAULT 0",
            "shipping": "BIGINT NOT NULL DEFAULT 300",
            "advance": "BIGINT NOT NULL DEFAULT 0",
            "remaining": "BIGINT NOT NULL DEFAULT 0",
            "delivery_amount": "BIGINT NOT NULL DEFAULT 0",
            "total": "BIGINT NOT NULL DEFAULT 0",
            "payment_status": "TEXT NOT NULL DEFAULT 'Pending Verification'",
            "email_sent_at": "TEXT DEFAULT NULL",
            "payment_preference": "TEXT NOT NULL DEFAULT '50% Advance'",
            "transaction_id": "TEXT DEFAULT NULL",
            "payment_proof": "TEXT DEFAULT NULL"
        }
        existing = {
            row["column_name"] for row in connection.execute("""
                SELECT column_name FROM information_schema.columns
                WHERE table_schema = current_schema() AND table_name = 'orders'
            """).fetchall()
        }
        for column, definition in migrations.items():
            if column not in existing:
                connection.execute(f'ALTER TABLE orders ADD COLUMN "{column}" {definition}')
        connection.execute("""
            CREATE TABLE IF NOT EXISTS subscribers (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                subscription_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
