@app.route("/admin/payment-proof/<int:order_id>")
@admin_required
def view_payment_proof(order_id):
    with get_connection() as connection:
        order = connection.execute(
            "SELECT payment_proof FROM orders WHERE id = %s",
            (order_id,)
        ).fetchone()

    if not order or not order["payment_proof"]:
        abort(404)

    proof = order["payment_proof"]

    if proof.startswith("cloudinary:"):
        public_id = proof.split(":", 1)[1]
        signed_url, _ = cloudinary.utils.cloudinary_url(
            public_id,
            resource_type="image",
            type="authenticated",
            sign_url=True,
            secure=True
        )
        return redirect(signed_url)

    if proof.startswith("local:"):
        filename = os.path.basename(proof.split(":", 1)[1])
        return send_from_directory(
            LOCAL_PROOF_DIR,
            filename,
            as_attachment=False
        )

    abort(404)

    


