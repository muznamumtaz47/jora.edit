@app.route("/api/place-order", methods=["POST"])
def place_order():
    name = request.form.get("name", "").strip()
    phone = request.form.get("phone", "").strip()
    email = request.form.get("email", "").strip().lower()
    city = request.form.get("city", "").strip()
    address = request.form.get("address", "").strip()
    payment = request.form.get("payment_method", "").strip()
    preference = request.form.get("payment_preference", "").strip()
    transaction_id = request.form.get("transaction_id", "").strip()
    try:
        products = json.loads(request.form.get("products", "[]"))
    except (json.JSONDecodeError, TypeError):
        return jsonify(success=False, message="Invalid product information."), 400
    if not all((name, phone, city, address)):
        return jsonify(success=False, message="Please complete all required delivery fields."), 400
    if not re.fullmatch(r"[0-9+\-\s()]{10,20}", phone):
        return jsonify(success=False, message="Please enter a valid phone number."), 400
    if email and not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
        return jsonify(success=False, message="Please enter a valid email address."), 400
    if payment not in ALLOWED_PAYMENT_METHODS:
        return jsonify(success=False, message="Please select a valid payment method."), 400
    if preference not in ALLOWED_PAYMENT_PREFERENCES:
        return jsonify(success=False, message="Please select 50% Advance or Full Payment."), 400
    if not transaction_id or len(transaction_id) > 100:
        return jsonify(success=False, message="Please enter a valid transaction ID."), 400
    try:
        amounts = calculate_order(products, preference)
        image_bytes, extension = validate_payment_screenshot(request.files.get("payment_screenshot"))
    except ValueError as error:
        return jsonify(success=False, message=str(error)), 400
    try:
        proof_reference = save_payment_proof(image_bytes, extension)
        with get_connection() as connection:
            row = connection.execute("""
                INSERT INTO orders (
                    customer_name, phone, email, city, address, payment_method, products,
                    status, subtotal, shipping, advance, remaining, delivery_amount, total,
                    payment_status, payment_preference, transaction_id, payment_proof
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING id
            """, (
                name, phone, email or None, city, address, payment,
                json.dumps(amounts["products"]), "Pending", amounts["subtotal"],
                amounts["shipping"], amounts["advance"], amounts["remaining"],
                amounts["delivery_amount"], amounts["total"], "Pending Verification",
                preference, transaction_id, proof_reference
            )).fetchone()
            order_id = row["id"]
    except Exception as error:
        print("Order database error:", error)
        return jsonify(success=False, message="Unable to save your order. Please try again."), 500
    return jsonify(
        success=True, message="Your order has been received!", order_id=order_id,
        advance=amounts["advance"], total=amounts["total"],
        delivery_amount=amounts["delivery_amount"], payment_method=payment,
        payment_preference=preference
    )

