def send_confirmation_email(order_id):
    try:
        with get_connection() as connection:
            order = connection.execute("SELECT * FROM orders WHERE id = %s", (order_id,)).fetchone()
            if not order or order["status"] != "Confirmed" or order["payment_status"] != "Verified" or not order["email"] or order["email_sent_at"]:
                return
            sender = os.environ.get("JORA_EMAIL_ADDRESS")
            password = os.environ.get("JORA_EMAIL_APP_PASSWORD")
            if not sender or not password:
                print("Confirmation email skipped: email credentials are not configured.")
                return
            if order["payment_preference"] == "Full Payment":
                payment_message = f"Full Payment Received: PKR {order['advance']:,}\nRemaining on Delivery: PKR 0"
            else:
                payment_message = f"Advance Payment: PKR {order['advance']:,}\nRemaining on Delivery: PKR {order['delivery_amount']:,}"
            message = EmailMessage()
            message["Subject"] = f"Your JORA.EDIT Order #{order_id} is Confirmed"
            message["From"] = sender
            message["To"] = order["email"]
            message.set_content(f"""Hello {order['customer_name']},

Thank you for choosing JORA.EDIT!
Your payment has been verified and your order is confirmed.

Order Number: #{order_id}
Order Total: PKR {order['total']:,}
{payment_message}

ROOTED IN TRADITION, MADE FOR TODAY.
JORA.EDIT
""")
            with smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=20) as server:
                server.login(sender, password)
                server.send_message(message)
            connection.execute("UPDATE orders SET email_sent_at = %s WHERE id = %s", (datetime.now().isoformat(), order_id))
    except Exception as error:
        print("Email sending failed:", error)


