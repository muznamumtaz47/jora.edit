@app.route("/api/subscribe", methods=["POST"])
def subscribe():
    data = request.get_json(silent=True)
    if not isinstance(data, dict) or not isinstance(data.get("email"), str):
        return jsonify(success=False, message="Please enter a valid email."), 400
    email = data["email"].strip().lower()
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
        return jsonify(success=False, message="Please enter a valid email address."), 400
    try:
        with get_connection() as connection:
            result = connection.execute(
                "INSERT INTO subscribers (email) VALUES (%s) ON CONFLICT (email) DO NOTHING RETURNING id",
                (email,)
            ).fetchone()
        if result:
            return jsonify(success=True, message="Thank you for subscribing to JORA.EDIT!")
        return jsonify(success=True, message="You are already subscribed!")
    except Exception as error:
        print("Newsletter database error:", error)
        return jsonify(success=False, message="Unable to save your subscription. Please try again."), 500


